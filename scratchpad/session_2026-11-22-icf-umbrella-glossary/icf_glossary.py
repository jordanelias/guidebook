import csv, collections, sqlite3, sys
D = 'scratchpad/session_2026-11-22-icf-umbrella-glossary/'
rows = list(csv.reader(open(D + 'who/SimpleTabulation-ICF-en.txt', encoding='utf-8-sig'), delimiter='\t'))
h = rows[0]; R = [dict(zip(h, r)) for r in rows[1:]]
clean = lambda t: t.strip('"').lstrip('- ').strip()
def dep(t):
    t = t.strip('"'); n = 0
    while t.startswith('- '): t = t[2:]; n += 1
    return n
q = next(i for i, r in enumerate(R) if r['ClassKind'] == 'chapter' and i > 0)   # second chapter = ICF Qualifier, not a category tree
R = R[:q]
# pre-order listing: the dashes in Title give depth, so ancestry is a stack
stack = []
for r in R:
    d = dep(r['Title']); del stack[d:]
    r['anc'] = list(stack); r['kids'] = []
    if stack: stack[-1]['kids'].append(r)
    stack.append(r)
anc = lambda r: r['anc']
code = {r['Code']: r for r in R if r['Code']}
deepest = lambda r: [a for a in anc(r) if a['ClassKind'] == 'block'][-1]
leafblock = lambda r: r['ClassKind'] == 'block' and not any(k['ClassKind'] == 'block' for k in r['kids'])
def cats(r):
    s = []
    for k in r['kids']:
        if k['Code']: s.append(k['Code'])
        s += cats(k)
    return s
def span(r):
    cs = sorted({c for c in cats(r) if len(c) == 4})
    return f"{cs[0]}–{cs[-1]}" if cs else ''
con = sqlite3.connect('file:data/guidebook.db?mode=ro', uri=True)
base = con.execute('select icf_code,title,is_range from base_icf order by icf_code').fetchall()
o = ["# ICF umbrellas and the codes `base_icf` holds under each\n",
     "Source: WHO ICF release 2026-01, `SimpleTabulation-ICF-en.zip`, retrieved through `retrieval_log` (sha256 in `retrieval-log/session_2026-11-22-icf-umbrella-glossary/manifest.jsonl`). Titles below are WHO's; the database's stored titles are shown beside them only where they differ. Generated by `icf_glossary.py`; re-run rather than trust.\n",
     "Blocks nest up to three levels (component, group, block). The umbrellas you name (*Movement functions*, *Pain*, *Hearing and vestibular functions*) are blocks; where a block has no block beneath it, it is the umbrella a category sits in.\n"]
# per L3 block: base codes bundled
bund = collections.defaultdict(list); unplaced = []
for c, t, rng in base:
    if rng:
        lo, hi = c.replace('–', '-').split('-')
        inside = [x for x in code if len(x) == 4 and x[0] == lo[0] and lo <= x <= hi]
        blks = sorted({(deepest(code[x])['BlockId'], clean(deepest(code[x])['Title'])) for x in inside})
        unplaced.append((c, t, blks)); continue
    r = code.get(c)
    if not r: unplaced.append((c, t, None)); continue
    bl = [a for a in anc(r) if a['ClassKind'] == 'block']
    key = bl[-1]['BlockId'] if bl else None
    bund[key].append((c, clean(r['Title']), t))
o.append("## 1. Umbrellas that hold at least one stored code\n")
for blk in sorted(b for b in bund if b):
    r = next(x for x in R if x['BlockId'] == blk)
    path = ' › '.join(clean(a['Title']) for a in anc(r) if a['ClassKind'] == 'block')
    o.append(f"### {clean(r['Title'])} ({span(r)})\n{path}\n")
    o.append("| code | WHO title | stored title differs |\n|---|---|---|")
    for c, wt, st in bund[blk]:
        diff = '' if (st or '').strip().lower() == wt.lower() else ('(none stored)' if not st else st[:70])
        o.append(f"| {c} | {wt} | {diff} |")
    o.append("")
o.append("## 2. Stored ranges, and the umbrellas they span\n")
for c, t, blks in unplaced:
    if blks is None: o.append(f"- {c}: not found in WHO tabulation"); continue
    o.append(f"- **{c}** spans: " + '; '.join(f"{b} {n}" for b, n in blks))
o.append("\n## 3. Full umbrella list (every block that has no block beneath it, with the 3-digit-category span and how many stored codes sit under it)\n")
o.append("| L1 | L2 | L3 umbrella | span | stored codes |\n|---|---|---|---|---|")
for r in R:
    if leafblock(r):
        a = [clean(x['Title']) for x in anc(r) if x['ClassKind'] == 'block']
        o.append(f"| {a[0]} | {a[1] if len(a)>1 else ''} | {clean(r['Title'])} | {span(r)} | {len(bund.get(r['BlockId'], []))} |")
open(D + 'icf-umbrellas.md', 'w').write('\n'.join(o))
print(len(bund), len(unplaced), sum(1 for r in R if leafblock(r)))
