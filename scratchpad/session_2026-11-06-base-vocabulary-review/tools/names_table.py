#!/usr/bin/env python3
"""Concept x language-and-jurisdiction table, generated from the terminology passes' own TSVs
(terminology-pass/<PAIR>/{coverage,observations,seeds}.tsv). Cell = phrases the instrument itself
uses (verbatim); [seed] = model-generated search seed, NOT a finding; a dash = read and absent / not read."""
import csv, glob, os, re, collections
ROOT='/home/user/guidebook/scratchpad/session_2026-11-06-base-vocabulary-review'
TP=f'{ROOT}/terminology-pass'
def rd(p):
    return list(csv.reader(open(p,encoding='utf-8'),delimiter='\t')) if os.path.exists(p) else []
def col(h,*names):
    for n in names:
        for i,x in enumerate(h):
            if x.lower().startswith(n): return i
    return None
def key(label):
    l=re.sub(r'^\d\.\d\s+','',label.strip()); l=l.split(' [also')[0]
    return re.sub(r'\s+',' ',l).strip().lower()
pairs=sorted(d for d in os.listdir(TP) if re.match(r'^[A-Z]{2}-',d) and os.path.exists(f'{TP}/{d}/coverage.tsv'))
order=[];label_of={}
data={}
for p in pairs:
    cov=rd(f'{TP}/{p}/coverage.tsv'); h=cov[0]
    ci=col(h,'concept_label','register_concept','concept'); si=col(h,'status')
    status={}
    for r in cov[1:]:
        if len(r)<=max(ci,si): continue
        k=key(r[ci]); status[k]=r[si].strip(); label_of.setdefault(k,re.sub(r'^\d\.\d\s+','',r[ci]).strip())
        if k not in order: order.append(k)
    ob=rd(f'{TP}/{p}/observations.tsv'); oh=ob[0] if ob else []
    oc=col(oh,'concept_label','concept'); pc=col(oh,'phrase') 
    phr=collections.defaultdict(list)
    for r in ob[1:]:
        if oc is None or pc is None or len(r)<=max(oc,pc): continue
        if 'REVERSE' in r[oc].upper(): continue
        for lab in re.split(r'\|',r[oc]):
            k=key(lab)
            if r[pc] and r[pc] not in phr[k]: phr[k].append(r[pc])
    sd=rd(f'{TP}/{p}/seeds.tsv'); seeds={}
    if sd:
        sh=sd[0]; sc=col(sh,'concept_label','register_concept','concept'); st=col(sh,'seed')
        for r in sd[1:]:
            if sc is not None and st is not None and len(r)>max(sc,st): seeds.setdefault(key(r[sc]),r[st])
    if p=='EN-VARIANTS':
        # English is one language in several jurisdictions: split into one column per jurisdiction
        ji=col(oh,'jurisdiction'); phj=collections.defaultdict(lambda: collections.defaultdict(list))
        for r in ob[1:]:
            if oc is None or pc is None or ji is None or len(r)<=max(oc,pc,ji) or 'REVERSE' in r[oc].upper(): continue
            for lab in re.split(r'\|',r[oc]):
                if r[pc] and r[pc] not in phj[r[ji]][key(lab)]: phj[r[ji]][key(lab)].append(r[pc])
        stj=collections.defaultdict(dict)
        for r in cov[1:]:
            if len(r)<=max(ci,si): continue
            for i,x in enumerate(h):
                m=re.match(r'^([A-Z]{2}) \(',x)
                if m and i<len(r): stj[m.group(1)][key(r[ci])]=r[i].strip()
        for j in sorted(phj):
            data[f'EN-{j}']=(stj[j],phj[j],{})
        continue
    data[p]=(status,phr,seeds)
def cell(p,k):
    status,phr,seeds=data[p]; s=status.get(k,'')
    if phr.get(k): return ' / '.join(phr[k][:4])+(' (partial)' if 'PARTIAL' in s else '')
    if k in seeds: return '[seed] '+seeds[k]
    if 'ABSENT' in s: return '— absent'
    if s: return '— '+s.lower()
    return ''
hdr=['concept (English register, Canadian wording)']+pairs
pairs=sorted(data)
rows=[[label_of[k]]+[cell(p,k) for p in pairs] for k in order]
with open(f'{ROOT}/concept-names-table.tsv','w',encoding='utf-8') as f:
    f.write('\t'.join(hdr)+'\n')
    for r in rows: f.write('\t'.join(c.replace('\t',' ') for c in r)+'\n')
with open(f'{ROOT}/concept-names-table.md','w',encoding='utf-8') as f:
    f.write('# Concept names by language and jurisdiction\n\nGenerated by `tools/names_table.py` from `terminology-pass/<pair>/*.tsv` (re-run, do not edit). **A phrase without a mark is verbatim in a retrieved instrument of that jurisdiction in its own language.** `[seed]` is a model-generated search seed, not a finding. `— absent` means the instrument was read and does not treat the concept; `— not-read` / `— not-obtainable` mean it could not be said. Pairs shown: '+', '.join(pairs)+'.\n\n')
    f.write('| '+' | '.join(hdr)+' |\n|'+'---|'*len(hdr)+'\n')
    for r in rows: f.write('| '+' | '.join(c.replace('|','/') for c in r)+' |\n')
print(len(rows),'concepts x',len(pairs),'pairs:',pairs)
